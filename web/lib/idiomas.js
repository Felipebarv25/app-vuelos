// Idioma por defecto según el navegador del usuario.
export function idiomaInicial() {
  if (typeof window === "undefined") return "es";
  const guardado = localStorage.getItem("idioma");
  if (guardado && T[guardado]) return guardado;
  const nav = (navigator.language || "es").slice(0, 2);
  return T[nav] ? nav : "es";
}

// Devuelve la función traductora t() para un idioma dado.
export function traductor(lang) {
  const dicc = T[lang] || T.es;
  return (clave, vars) => {
    let txt = dicc[clave] ?? T.es[clave] ?? clave;
    if (vars) for (const k in vars) txt = txt.replace(`{${k}}`, vars[k]);
    return txt;
  };
}
